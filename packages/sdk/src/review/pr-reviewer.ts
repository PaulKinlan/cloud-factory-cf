/**
 * Core PR Reviewer Bot & LLM Review Synthesis.
 *
 * Implements the end-to-end pull_request review flow:
 * Pull Request Event -> Diff Fetch -> LLM / Heuristic Review -> GitHub PR Review / Comment.
 */

import type { AgentExecutionFn, AgentExecutionInput, AgentExecutionOutput } from '../runtime/agent-runtime.ts';
import type { PullRequestInfo, ReviewResult, ReviewFinding, ReviewVerdict, PrReviewerOptions, LlmClient } from './types.ts';
import { analyzeUnifiedDiff } from './diff-analyzer.ts';

const MAX_DIFF_CHARS_FOR_LLM = 40_000;

export function buildReviewMarkdown(options: {
  readonly info: PullRequestInfo;
  readonly verdict: ReviewVerdict;
  readonly summary: string;
  readonly findings: readonly ReviewFinding[];
  readonly files: readonly string[];
  readonly additions: number;
  readonly deletions: number;
  readonly instruction?: string;
}): string {
  const { info, verdict, summary, findings, files, additions, deletions, instruction } = options;

  const verdictBadge =
    verdict === 'APPROVE'
      ? '✅ **APPROVE**'
      : verdict === 'REQUEST_CHANGES'
      ? '🚨 **REQUEST CHANGES**'
      : '💬 **COMMENT**';

  const lines: string[] = [
    `## 🤖 Cloud Factory PR Review: #${info.number} ${info.title ? `— *${info.title}*` : ''}`,
    '',
    `**Verdict:** ${verdictBadge}`,
    '',
    '### 📋 Overview',
    summary,
    '',
    '### 📊 Diff Summary',
    `- **Files Changed:** ${files.length}`,
    `- **Lines Added:** +${additions}`,
    `- **Lines Deleted:** -${deletions}`,
  ];

  if (files.length > 0 && files.length <= 15) {
    lines.push('', '<details><summary>Changed Files</summary>', '');
    for (const f of files) {
      lines.push(`- \`${f}\``);
    }
    lines.push('', '</details>');
  }

  lines.push('', '### 🔍 Key Findings & Recommendations');
  if (findings.length === 0) {
    lines.push('- No critical issues, security leaks, or code smells identified. Changes appear clean and well-structured.');
  } else {
    for (const f of findings) {
      const icon = f.severity === 'error' ? '❌' : f.severity === 'warning' ? '⚠️' : 'ℹ️';
      const fileRef = f.file ? ` (\`${f.file}\`${f.line ? `:${f.line}` : ''})` : '';
      lines.push(`- ${icon} **[${f.category.toUpperCase()}]** ${f.message}${fileRef}`);
    }
  }

  if (instruction) {
    lines.push('', `> *Review evaluated under custom instruction: "${instruction}"*`);
  }

  lines.push(
    '',
    '---',
    '*Automated review generated by Cloud Factory CF Core PR Reviewer Bot.*'
  );

  return lines.join('\n');
}

export function generatePrReviewPrompt(
  info: PullRequestInfo,
  diff: string,
  instruction?: string
): { systemPrompt: string; userPrompt: string } {
  const truncatedDiff =
    diff.length > MAX_DIFF_CHARS_FOR_LLM
      ? `${diff.slice(0, MAX_DIFF_CHARS_FOR_LLM)}\n\n...[diff truncated for length]`
      : diff;

  const systemPrompt = [
    'You are an expert autonomous software engineer and strict code reviewer for Cloud Factory CF.',
    'Your goal is to provide a constructive, thorough, and highly accurate code review.',
    'Analyze the supplied git diff for:',
    '1. Correctness, bugs, edge cases, and unexpected side effects.',
    '2. Security vulnerabilities, credential leaks, and injection vectors.',
    '3. Test coverage: whether new code has accompanying tests.',
    '4. Clean architecture and readability.',
    '',
    'Respond in JSON format with:',
    '{',
    '  "verdict": "APPROVE" | "COMMENT" | "REQUEST_CHANGES",',
    '  "summary": "1-3 paragraphs summarizing the PR intent and key architectural changes.",',
    '  "findings": [',
    '    { "category": "security" | "test" | "dependency" | "quality" | "general", "severity": "error" | "warning" | "info", "message": "description" }',
    '  ]',
    '}',
  ].join('\n');

  const userPrompt = [
    `Review PR #${info.number}: "${info.title}" in repository "${info.repository ?? 'current'}".`,
    info.author ? `Author: ${info.author}` : '',
    info.baseRef && info.headRef ? `Branch: ${info.headRef} -> ${info.baseRef}` : '',
    instruction ? `Specific review directive: "${instruction}"` : '',
    '',
    '### Pull Request Diff:',
    '```diff',
    truncatedDiff || '(empty diff)',
    '```',
  ]
    .filter(Boolean)
    .join('\n');

  return { systemPrompt, userPrompt };
}

function parseLlmOutput(
  rawText: string
): { verdict?: ReviewVerdict; summary?: string; findings?: ReviewFinding[] } | null {
  try {
    const jsonMatch = rawText.match(/\{[\s\S]*\}/);
    if (!jsonMatch) return null;
    const parsed = JSON.parse(jsonMatch[0]) as {
      verdict?: string;
      summary?: string;
      findings?: Array<{ category?: string; severity?: string; message?: string }>;
    };

    let verdict: ReviewVerdict | undefined;
    if (parsed.verdict === 'APPROVE' || parsed.verdict === 'COMMENT' || parsed.verdict === 'REQUEST_CHANGES') {
      verdict = parsed.verdict;
    }

    const findings: ReviewFinding[] = [];
    if (Array.isArray(parsed.findings)) {
      for (const item of parsed.findings) {
        if (typeof item?.message === 'string' && item.message.trim().length > 0) {
          const category =
            item.category === 'security' ||
            item.category === 'test' ||
            item.category === 'dependency' ||
            item.category === 'quality'
              ? item.category
              : 'general';
          const severity =
            item.severity === 'error' || item.severity === 'warning' || item.severity === 'info'
              ? item.severity
              : 'warning';
          findings.push({ category, severity, message: item.message.trim() });
        }
      }
    }

    return {
      verdict,
      summary: typeof parsed.summary === 'string' ? parsed.summary.trim() : undefined,
      findings,
    };
  } catch {
    return null;
  }
}

export async function generatePrReview(
  info: PullRequestInfo,
  diff: string,
  options: PrReviewerOptions = {}
): Promise<ReviewResult> {
  const analysis = analyzeUnifiedDiff(diff);
  const findings: ReviewFinding[] = [];

  // Deterministic guardrails (fail-closed security checks)
  for (const secret of analysis.secretFindings) {
    findings.push({
      category: 'security',
      severity: 'error',
      message: secret,
    });
  }

  if (analysis.hasPackageJsonChanges && !analysis.hasLockfileChanges) {
    findings.push({
      category: 'dependency',
      severity: 'error',
      message: '`package.json` was modified without updating `package-lock.json` or lockfile.',
    });
  }

  if (analysis.hasSourceChanges && !analysis.hasTestChanges) {
    findings.push({
      category: 'test',
      severity: 'warning',
      message: 'Source code was modified without accompanying test additions or updates.',
    });
  }

  for (const debug of analysis.debugStatements) {
    findings.push({
      category: 'quality',
      severity: 'warning',
      message: debug,
    });
  }

  let verdict: ReviewVerdict = 'APPROVE';
  let summary = '';

  // Determine baseline verdict from deterministic findings
  const hasErrors = findings.some((f) => f.severity === 'error');
  const hasWarnings = findings.some((f) => f.severity === 'warning');

  if (hasErrors) {
    verdict = 'REQUEST_CHANGES';
  } else if (hasWarnings) {
    verdict = 'COMMENT';
  } else {
    verdict = options.defaultVerdict ?? 'APPROVE';
  }

  // If an LLM client is supplied, run synthesis through the model
  if (options.llmClient) {
    try {
      const { systemPrompt, userPrompt } = generatePrReviewPrompt(info, diff, options.instruction);
      const rawOutput = await options.llmClient(userPrompt, systemPrompt);
      const parsedLlm = parseLlmOutput(rawOutput);

      if (parsedLlm) {
        if (parsedLlm.summary) {
          summary = parsedLlm.summary;
        }
        if (parsedLlm.findings && parsedLlm.findings.length > 0) {
          findings.push(...parsedLlm.findings);
        }
        // If LLM requested changes or security checks failed, escalate verdict
        if (hasErrors || parsedLlm.verdict === 'REQUEST_CHANGES') {
          verdict = 'REQUEST_CHANGES';
        } else if (parsedLlm.verdict === 'COMMENT' || hasWarnings) {
          verdict = 'COMMENT';
        } else if (parsedLlm.verdict === 'APPROVE' && !hasWarnings && !hasErrors) {
          verdict = 'APPROVE';
        }
      } else if (rawOutput && rawOutput.trim().length > 0) {
        summary = rawOutput.trim();
      }
    } catch (err: unknown) {
      // Fail closed (cloud-factory-cf-r9b): a model that cannot answer must not be
      // turned into a template review that reads as if the model had reviewed.
      const msg = err instanceof Error ? err.message : String(err);
      throw new Error(`model review failed: ${msg}`);
    }
  }

  // Fallback summary synthesis if LLM didn't supply one
  if (!summary) {
    if (analysis.files.length === 0) {
      summary = `PR #${info.number} contains no file modifications or an empty diff.`;
    } else {
      const fileList = analysis.files.slice(0, 5).map((f) => `\`${f}\``).join(', ');
      const extra = analysis.files.length > 5 ? ` and ${analysis.files.length - 5} other file(s)` : '';
      summary = `PR #${info.number} introduces ${analysis.additions} addition(s) and ${analysis.deletions} deletion(s) across ${analysis.files.length} file(s) (${fileList}${extra}).`;
    }
  }

  const markdown = buildReviewMarkdown({
    info,
    verdict,
    summary,
    findings,
    files: analysis.files,
    additions: analysis.additions,
    deletions: analysis.deletions,
    instruction: options.instruction,
  });

  return {
    prNumber: info.number,
    verdict,
    summary,
    findings,
    markdown,
    diffAnalysis: analysis,
  };
}

/**
 * Creates an AgentExecutionFn that acts as the Core PR Reviewer Bot.
 * It fetches the pull request diff via the CredentialBroker capability ('pr.diff'),
 * synthesizes a code review, and emits a GitHub PR review to configured sinks.
 */
export function createPrReviewerExecutionFn(options: PrReviewerOptions = {}): AgentExecutionFn {
  return async (input: AgentExecutionInput): Promise<AgentExecutionOutput> => {
    const { ctx } = input;
    const facts = ctx.state['event'] as Record<string, unknown> | undefined;

    if (!facts || typeof facts !== 'object') {
      return { status: 'failure', error: 'No event facts in run context', toolCallsCount: 0 };
    }

    const eventName = String(facts['event'] ?? '');
    const actionName = typeof facts['action'] === 'string' ? facts['action'] : '';
    const prNumber =
      typeof facts['number'] === 'number'
        ? facts['number']
        : typeof (facts['payload'] as any)?.['number'] === 'number'
        ? (facts['payload'] as any)['number']
        : undefined;

    const providerName = typeof facts['provider'] === 'string' ? facts['provider'] : 'github';
    if (providerName !== 'github') {
      // The engine's broker actions are GitHub routes, so anything else must be
      // skipped rather than pointed at the wrong forge (cloud-factory-cf-6sa).
      return {
        status: 'success',
        output: `Skipped ${providerName} event: this engine reviews GitHub pull requests`,
        toolCallsCount: 0,
      };
    }

    if (eventName !== 'pull_request' || typeof prNumber !== 'number' || prNumber <= 0) {
      // Not a reviewable pull request event
      return {
        status: 'success',
        output: `Skipped non-pull_request event: ${eventName}.${actionName || '-'}`,
        toolCallsCount: 0,
      };
    }

    const repoFullName =
      typeof facts['repository'] === 'string'
        ? facts['repository']
        : ctx.repo
        ? `${ctx.repo.owner}/${ctx.repo.name}`
        : 'unknown';

    const payload = (facts['payload'] ?? {}) as Record<string, unknown>;
    const pullRequest = (payload['pull_request'] ?? {}) as Record<string, unknown>;
    const prTitle =
      typeof facts['title'] === 'string'
        ? facts['title']
        : typeof pullRequest['title'] === 'string'
        ? pullRequest['title']
        : `PR #${prNumber}`;
    const prAuthor = typeof (pullRequest['user'] as any)?.['login'] === 'string' ? (pullRequest['user'] as any)['login'] : undefined;
    const baseRef = typeof (pullRequest['base'] as any)?.['ref'] === 'string' ? (pullRequest['base'] as any)['ref'] : undefined;
    const headRef = typeof (pullRequest['head'] as any)?.['ref'] === 'string' ? (pullRequest['head'] as any)['ref'] : undefined;
    const commitSha = typeof (pullRequest['head'] as any)?.['sha'] === 'string' ? (pullRequest['head'] as any)['sha'] : undefined;

    const info: PullRequestInfo = {
      number: prNumber,
      title: prTitle,
      author: prAuthor,
      repository: repoFullName,
      baseRef,
      headRef,
      commitSha,
    };

    // 0. Memory and Action Ledger Checks
    const memoryScope = ctx.state['memoryScope'] === 'org' ? 'org' : 'repo';
    let reviewCount = 0;
    if (ctx.memory) {
      try {
        const previous = await ctx.memory.get(memoryScope, 'review-count');
        reviewCount = typeof previous === 'number' ? previous + 1 : 1;
      } catch {
        // Swallow memory read error
      }
    }

    const ledger = ctx.state['actionLedger'] as {
      claim(actionType: string): Promise<'run' | 'skip' | 'unavailable'>;
      complete(actionType: string, status: 'delivered' | 'failed'): Promise<string | null>;
    } | undefined;

    const actionType = 'github:pr:review';
    const permission = ledger ? await ledger.claim(actionType) : 'run';
    if (permission === 'skip') {
      return {
        status: 'success',
        output: `Action ${actionType} was already delivered`,
        toolCallsCount: 0,
      };
    }
    if (permission === 'unavailable') {
      return {
        status: 'failure',
        error: 'Delivery ledger unavailable, so the review was not started',
        toolCallsCount: 0,
      };
    }

    // 1. Fetch Diff via CredentialBroker ('pr.diff')
    let diff = '';
    let diffFetched = false;

    try {
      const response = await ctx.credentials.executeSignedRequest<string>({
        service: 'github',
        action: 'pr.diff',
        params: { number: prNumber },
      });
      if (typeof response === 'string' && response.trim().length > 0) {
        diff = response;
        diffFetched = true;
      } else if (response && typeof response === 'object') {
        diff = JSON.stringify(response);
        diffFetched = true;
      }
    } catch {
      // Fallback: check if diff was embedded in event payload (e.g. mock or test webhook)
      if (typeof payload['diff'] === 'string') {
        diff = payload['diff'];
        diffFetched = true;
      }
    }

    if (!diffFetched) {
      // Fail closed (cloud-factory-cf-c23): reviewing nothing must never produce an
      // APPROVE. The event is retried instead.
      return {
        status: 'failure',
        error: 'could not read the pull-request diff',
        toolCallsCount: 0,
      };
    }

    // 2. Resolve LLM client and instructions
    const customPrompt = typeof ctx.state['agentPrompt'] === 'string' ? ctx.state['agentPrompt'] : options.instruction;
    const llmClient = (ctx.state['llmClient'] as LlmClient | undefined) ?? options.llmClient;

    // 3. Generate Review
    const review = await generatePrReview(info, diff, {
      ...options,
      instruction: customPrompt,
      llmClient,
    });

    // 4. Emit to Sinks (GitHub PR Review and/or PR Comment)
    const reviewAction = {
      id: `pr-review-${prNumber}-${Date.now()}`,
      type: 'github:pr:review',
      payload: {
        prNumber,
        event: review.verdict,
        body: review.markdown,
        commitSha,
      },
    };

    const emitResults = await ctx.sinks.emit(reviewAction, ctx);
    const failedSink = emitResults.find((r) => !r.success);

    if (ledger) {
      await ledger.complete(actionType, failedSink ? 'failed' : 'delivered');
    }

    if (failedSink) {
      return {
        status: 'failure',
        error: `Failed to post PR review: ${failedSink.error ?? 'unknown error'}`,
        toolCallsCount: diffFetched ? 1 : 0,
      };
    }

    if (ctx.memory && reviewCount > 0) {
      try {
        await ctx.memory.set(memoryScope, 'review-count', reviewCount, { event: facts['deliveryId'] });
      } catch {
        // Swallow memory write error
      }
    }

    return {
      status: 'success',
      output: review.markdown,
      toolCallsCount: diffFetched ? 1 : 0,
      metadata: {
        prNumber,
        verdict: review.verdict,
        filesCount: review.diffAnalysis.files.length,
        additions: review.diffAnalysis.additions,
        deletions: review.diffAnalysis.deletions,
      },
    };
  };
}
